// Node: node month-approval-tests.mjs (must run alongside emulator regression in CI)
import assert from 'node:assert/strict';
import {preliminaryPracticeDays,jstInputOpenMillis,jstInputCutoffMillis} from './month-rollover-core.mjs';
import {ROSTER} from './core.mjs';
import {normalizeMember} from './month-draft-core.mjs';
import {canReviewGeneratedMonth,reviewMonthlyDraft,monthApprovalPatch,publishMonthList} from './month-approval-core.mjs';
let n=0;
const check=(label,f)=>{f();n++;console.log('OK '+label)};
const month='2027-03',members=ROSTER.map(normalizeMember);
const meta={publication:'draft',autoGenerated:true,openAt:{toMillis:()=>jstInputOpenMillis(month)},cutoffAt:{toMillis:()=>jstInputCutoffMillis(month)}};
const all=()=>preliminaryPracticeDays(month).map(d=>({
 ...d,ownerId:d.weekday===3?'yui':d.weekday===5?'kaho':d.weekday===6?'mia':'an',
 activityVerified:true
}));
check('generated month is initially hidden',()=>assert.notEqual(meta.publication,'published'));
check('march requires explicit manager approval',()=>assert.equal(canReviewGeneratedMonth(month),true));
check('December confirmed schedule excluded',()=>assert.equal(canReviewGeneratedMonth('2026-12'),false));
check('January existing draft excluded',()=>assert.equal(canReviewGeneratedMonth('2027-01'),false));
check('outside season is excluded',()=>assert.equal(canReviewGeneratedMonth('2027-12'),false));
check('valid checked draft can be reviewed',()=>assert.equal(reviewMonthlyDraft({month,meta,days:all(),members}).ok,true));
check('unverified calendar blocks publication',()=>{
 const days=all();days[0].activityVerified=false;
 assert.ok(reviewMonthlyDraft({month,meta,days,members}).errors.some(x=>x.includes('未確認')));
});
check('missing assignee blocks publication',()=>{
 const days=all();days[0].ownerId=null;
 assert.equal(reviewMonthlyDraft({month,meta,days,members}).ok,false);
});
check('wrong weekday (Mia on Wednesday) blocks',()=>{
 const days=all();days.find(d=>d.weekday===3).ownerId='mia';
 assert.equal(reviewMonthlyDraft({month,meta,days,members}).ok,false);
});
check('Sawa must not be scheduled Friday',()=>{
 const days=all();days.find(d=>d.weekday===5).ownerId='sawa';
 assert.equal(reviewMonthlyDraft({month,meta,days,members}).ok,false);
});
check('game day needs no owner, if verified',()=>{
 const days=all();days[0].type='game';days[0].ownerId=null;
 assert.equal(reviewMonthlyDraft({month,meta,days,members}).ok,true);
});
check('game day assigned owner blocks publication',()=>{
 const days=all();days[0].type='game';
 assert.equal(reviewMonthlyDraft({month,meta,days,members}).ok,false);
});
check('rest day needs no owner, if verified',()=>{
 const days=all();days[0].type='rest';days[0].ownerId=null;
 assert.equal(reviewMonthlyDraft({month,meta,days,members}).ok,true);
});
check('missing day cannot be published',()=>{
 const days=all();days.pop();
 assert.equal(reviewMonthlyDraft({month,meta,days,members}).ok,false);
});
check('extra day cannot be published',()=>{
 const days=all();days.push({...days[0],date:'2027-03-01'});
 assert.equal(reviewMonthlyDraft({month,meta,days,members}).ok,false);
});
check('duplicate day cannot be published',()=>{
 const days=all();days.push({...days[0]});
 assert.equal(reviewMonthlyDraft({month,meta,days,members}).ok,false);
});
check('non-draft month cannot approve',()=>{
 assert.equal(reviewMonthlyDraft({month,meta:{...meta,publication:'published'},days:all(),members}).ok,false);
});
check('non-generated month cannot approve',()=>{
 assert.equal(reviewMonthlyDraft({month,meta:{...meta,autoGenerated:false},days:all(),members}).ok,false);
});
check('approved publication is explicit published',()=>{
 const data=monthApprovalPatch({month,meta,nowMillis:jstInputOpenMillis(month)+10});
 assert.equal(data.publication,'published');
 assert.equal(data.scheduleStatus,'provisional-published');
 assert.equal(data.scheduleVerified,true);
 assert.equal(data.inputState,'open');
});
check('approved month after cutoff is read only',()=>{
 const data=monthApprovalPatch({month,meta,nowMillis:jstInputCutoffMillis(month)});
 assert.equal(data.inputState,'closed');
});
check('cannot approve old or non-draft month',()=>{
 assert.throws(()=>monthApprovalPatch({month:'2026-12',meta}));
 assert.throws(()=>monthApprovalPatch({month,meta:{...meta,publication:'published'}}));
});
check('publishedMonths remains unchanged until admin publication',()=>{
 const before=['2026-12'],approved=publishMonthList(before,month);
 assert.deepEqual(before,['2026-12']);
 assert.deepEqual(approved,['2026-12','2027-03']);
});
check('repeat approval does not duplicate month',()=>{
 assert.deepEqual(publishMonthList(['2026-12','2027-03'],month),['2026-12','2027-03']);
});
console.log('PASS '+n+' manager-only publication safeguard tests');
