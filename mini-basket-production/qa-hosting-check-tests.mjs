import assert from 'node:assert/strict';
import {getQaDefaultHostingSite} from './qa-hosting-check.mjs';
import {readFile} from 'node:fs/promises';
const project='basket-staging-qa';
const site={name:'projects/'+project+'/sites/'+project,type:'DEFAULT_SITE'};
const siteAlternate={siteId:project,type:'DEFAULT_SITE'};
const ok=(x,p=project)=>getQaDefaultHostingSite(x,p);
assert.deepEqual(ok({status:'success',result:[site]}),site);
assert.deepEqual(ok({result:{sites:[siteAlternate]}}),siteAlternate);
assert.deepEqual(ok(JSON.stringify({result:[site]})),site);
assert.throws(()=>ok({result:[]}),/デフォルトHostingサイトがありません/);
assert.throws(()=>ok({result:[{...site,type:'USER_SITE'}]}),/デフォルトHostingサイトがありません/);
assert.throws(()=>ok({result:[{name:'projects/'+project+'/sites/other-site',type:'DEFAULT_SITE'}]}),/デフォルトHostingサイトがありません/);
assert.throws(()=>ok({status:'error',error:'permission'}),/一覧取得に失敗/);
assert.throws(()=>ok({result:{unexpected:[]}}),/一覧の形式/);
assert.throws(()=>ok({result:[site]},'aritama-mini-basket'));
const deploy=await readFile(new URL('./deploy-qa.mjs',import.meta.url),'utf8');
const hostingRead=deploy.indexOf(",'hosting:sites:list'");
const hostingWrite=deploy.indexOf(",'deploy'");
assert.ok(hostingRead>0&&hostingWrite>hostingRead,'must check Hosting site before deploy');
assert.match(deploy,/getQaDefaultHostingSite\(sites,opts\.project\)/);
console.log('PASS current Firebase default Hosting preflight and fail-closed QA deploy checks');
