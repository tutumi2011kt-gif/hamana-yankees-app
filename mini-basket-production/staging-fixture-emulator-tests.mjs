// End-to-end stage fixture smoke test with real Firebase Emulator security evaluation.
// No production access and no personal roster data.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {initializeTestEnvironment,assertSucceeds,assertFails} from '@firebase/rules-unit-testing';
import {doc,collection,getDoc,getDocs,setDoc,updateDoc,serverTimestamp,Timestamp} from 'firebase/firestore';
import {makeQaFixture} from './staging-fixture-core.mjs';
import {reviewMonthlyDraft,monthApprovalPatch,publishMonthList} from './month-approval-core.mjs';

const fx=makeQaFixture('basket-staging-qa');
const env=await initializeTestEnvironment({projectId:'demo-mini-basket',
 firestore:{rules:await readFile('firestore-parent-anonymous-write-candidate.rules','utf8')}
});
const root='teams/'+fx.teamId;
const toData=e=>{
 if(!e.path.includes('/months/')||e.path.includes('/days/'))return e.data;
 const {openAtMillis,cutoffAtMillis,...rest}=e.data;
 return {...rest,openAt:Timestamp.fromMillis(openAtMillis),cutoffAt:Timestamp.fromMillis(cutoffAtMillis)};
};
try{
 await env.clearFirestore();
 await env.withSecurityRulesDisabled(async context=>{
  const db=context.firestore();
  for(const entry of fx.entries){
   const data=toData(entry);
   // Only alter the emulator's clock window for repeatable CI execution after Dec 2026.
   if(entry.path===root+'/months/2027-01'){
    data.openAt=Timestamp.fromMillis(Date.now()-60_000);
    data.cutoffAt=Timestamp.fromMillis(Date.now()+60*60_000);
   }
   await setDoc(doc(db,entry.path),data);
  }
  await setDoc(doc(db,'admins/qa-admin-001'),{enabled:true,qaOnly:true});
 });
 const parent=env.authenticatedContext('qa-parent-001',{firebase:{sign_in_provider:'anonymous'}}).firestore();
 const helper=env.authenticatedContext('qa-parent-002',{firebase:{sign_in_provider:'anonymous'}}).firestore();
 const admin=env.authenticatedContext('qa-admin-001',{firebase:{sign_in_provider:'google.com'}}).firestore();
 const roster=await assertSucceeds(getDoc(doc(parent,root+'/public/roster')));
 assert.equal(roster.data().members.length,12);
 assert.deepEqual(roster.data().publishedMonths,['2027-01']);
 const jan=await assertSucceeds(getDoc(doc(parent,root+'/months/2027-01')));
 assert.equal(jan.data().publication,'published');
 const janDays=await assertSucceeds(getDocs(collection(parent,root+'/months/2027-01/days')));
 assert.equal(janDays.size,fx.janDays.length);
 await assertFails(getDoc(doc(parent,root+'/months/2027-03')));
 await assertFails(getDoc(doc(parent,root+'/months/2027-03/days/'+fx.marchDays[0].date)));
 await assertFails(getDoc(doc(parent,root+'/members/qa01')));
 const date=fx.janDays.find(d=>d.type==='practice'&&d.ownerId==='qa01').date;
 const a1=doc(parent,root+'/months/2027-01/answers/'+date+'_qa01');
 const a2=doc(helper,root+'/months/2027-01/answers/'+date+'_qa02');
 await assertSucceeds(setDoc(a1,{date,memberId:'qa01',kind:'x',updatedBy:'qa-parent-001',updatedAt:serverTimestamp()}));
 await assertSucceeds(setDoc(a2,{date,memberId:'qa02',kind:'o',updatedBy:'qa-parent-002',updatedAt:serverTimestamp()}));
 await assertFails(setDoc(doc(helper,root+'/months/2027-01/answers/'+date+'_qa01'),
  {date,memberId:'qa01',kind:'x',updatedBy:'qa-parent-002',updatedAt:serverTimestamp()}));
 assert.equal((await assertSucceeds(getDocs(collection(parent,root+'/months/2027-01/answers')))).size,2);
 console.log('PASS QA fixture: 12 fictitious members, public January, private March, valid anonymous answers');

 const march=fx.marchDays.map((d,i)=>({...d,type:'practice',
  ownerId:fx.members[i%fx.members.length].id,activityVerified:true}));
 const validation=reviewMonthlyDraft({
  month:'2027-03',meta:{publication:'draft',autoGenerated:true},days:march,members:fx.members
 });
 assert.equal(validation.ok,true,validation.errors.join('／'));
 for(const row of march){
  await assertSucceeds(updateDoc(doc(admin,root+'/months/2027-03/days/'+row.date),
   {ownerId:row.ownerId,activityVerified:true}));
 }
 const patch=monthApprovalPatch({month:'2027-03',meta:toData(fx.entries.find(x=>x.path===root+'/months/2027-03')),
  nowMillis:Date.now()});
 // Approval does not automatically enable answers before opening date.
 assert.equal(patch.publication,'published');
 await assertSucceeds(updateDoc(doc(admin,root+'/months/2027-03'),{
  ...patch,approvedBy:'qa-admin-001',approvedAt:serverTimestamp()
 }));
 await assertSucceeds(updateDoc(doc(admin,root+'/public/roster'),{
  publishedMonths:publishMonthList(roster.data().publishedMonths,'2027-03')
 }));
 assert.equal((await assertSucceeds(getDoc(doc(parent,root+'/months/2027-03')))).data().publication,'published');
 assert.ok((await assertSucceeds(getDoc(doc(parent,root+'/public/roster')))).data().publishedMonths.includes('2027-03'));
 console.log('PASS QA fixture: manager-only March draft becomes visible only after explicit approval');
}finally{
 await env.cleanup();
}
