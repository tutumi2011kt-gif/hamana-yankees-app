// Admin-only publication checks for calendar months generated on the first of a month.
// Draft storage is not approval; parents only see months explicitly published by an admin.
// No Firebase API or writes in this module.
import {preliminaryPracticeDays,validMonth} from './month-rollover-core.mjs';
import {isDayAllowed} from './weekday-conditions.mjs';

export const APPROVAL_FIRST_MONTH='2027-03';
export const APPROVAL_LAST_MONTH='2027-11';

export function canReviewGeneratedMonth(month){
 return validMonth(month)&&month>=APPROVAL_FIRST_MONTH&&month<=APPROVAL_LAST_MONTH;
}
export function reviewMonthlyDraft({month,meta,days,members}){
 const errors=[],notes=[];
 if(!canReviewGeneratedMonth(month))errors.push('月が当番管理期間外です（2027年3月〜11月）');
 if(!meta||meta.publication!=='draft')errors.push('管理者確認待ちの下書きではありません');
 if(meta?.autoGenerated!==true)errors.push('月初に自動生成されたカレンダーではありません');
 if(!Array.isArray(days)||!Array.isArray(members)){errors.push('日別予定またはメンバーが取得できていません');return {ok:false,errors,notes};}
 const expected=canReviewGeneratedMonth(month)?preliminaryPracticeDays(month):[];
 const byId=Object.fromEntries(members.map(m=>[m.id,m]));
 const expectedIds=new Set(expected.map(x=>x.date)),seen=new Set();
 if(days.length!==expected.length)errors.push('日別予定が不足・重複しています');
 for(const row of days){
  if(!row||typeof row.date!=='string'||!expectedIds.has(row.date)){errors.push('対象外の日付があります');continue;}
  if(seen.has(row.date)){errors.push(row.date+' が重複しています');continue;}
  seen.add(row.date);
  const correct=expected.find(x=>x.date===row.date);
  if(row.weekday!==correct.weekday)errors.push(row.date+' の曜日が異なります');
  if(!['practice','game','rest'].includes(row.type))errors.push(row.date+' の予定が不正です');
  if(row.activityVerified!==true)errors.push(row.date+' の練習・試合・休みが未確認です');
  if(row.type==='practice'){
   if(!row.ownerId)errors.push(row.date+' の当番担当者が未設定です');
   else if(!byId[row.ownerId])errors.push(row.date+' の担当者が現在の名簿にいません');
   else if(!isDayAllowed(byId[row.ownerId],row.date,row.weekday))errors.push(row.date+' の担当者は当番可能曜日・在籍期間に違反しています');
  }else if(row.ownerId!==null&&row.ownerId!==undefined&&row.ownerId!=='')errors.push(row.date+' は試合または休みなのに当番担当者がいます');
 }
 for(const d of expected)if(!seen.has(d.date))errors.push(d.date+' が存在しません');
 if(!errors.length)notes.push('すべての活動区分・担当者が確認済みです。管理者の公開承認を待っています。');
 return {ok:errors.length===0,errors,notes,days:expected.length,
  practice:days.filter(x=>x.type==='practice').length,
  game:days.filter(x=>x.type==='game').length,
  rest:days.filter(x=>x.type==='rest').length};
}
export function monthApprovalPatch({month,meta,nowMillis=Date.now()}){
 if(!canReviewGeneratedMonth(month))throw Error('対象月が不正です');
 if(meta?.publication!=='draft'||meta?.autoGenerated!==true)throw Error('自動生成された下書きのみ公開できます');
 const from=meta.openAt?.toMillis?.()??meta.openAt;
 const until=meta.cutoffAt?.toMillis?.()??meta.cutoffAt;
 if(!Number.isFinite(from)||!Number.isFinite(until)||from>=until)throw Error('受付期間が正しくありません');
 return {
  publication:'published',
  scheduleStatus:'provisional-published',
  scheduleVerified:true,
  inputState:nowMillis>=from&&nowMillis<until?'open':'closed'
 };
}
export function publishMonthList(previous,month){
 if(!canReviewGeneratedMonth(month)||!Array.isArray(previous)||previous.some(m=>!validMonth(m)))throw Error('公開月リストが不正です');
 return [...new Set([...previous,month])].sort();
}
