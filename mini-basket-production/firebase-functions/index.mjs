// Scheduled at 00:00 JST on day 1 of each month.
// Locking at the exact instant is already enforced separately by Firestore
// request.time against cutoffAt; this job materializes monthly calendar docs.
import {onSchedule} from 'firebase-functions/v2/scheduler';
import {initializeApp} from 'firebase-admin/app';
import {getFirestore,Timestamp,FieldValue} from 'firebase-admin/firestore';

initializeApp();
const db=getFirestore();
const TEAM='aritama-mini-basket';
function plus(month,n){
 const [y,m]=month.split('-').map(Number);
 return new Date(Date.UTC(y,m-1+n,1)).toISOString().slice(0,7);
}
const atJstStart=month=>Date.parse(month+'-01T00:00:00+09:00');
function clockInTokyo(now){
 const parts=Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Tokyo',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(now);
 const d=Object.fromEntries(parts.filter(x=>x.type!=='literal').map(x=>[x.type,x.value]));
 return {month:d.year+'-'+d.month,day:Number(d.day)};
}
function provisionalDays(month){
 const [year,m]=month.split('-').map(Number),last=new Date(Date.UTC(year,m,0)).getUTCDate();
 return Array.from({length:last},(_,i)=>{
  const day=i+1,date=month+'-'+String(day).padStart(2,'0');
  const weekday=new Date(Date.UTC(year,m-1,day)).getUTCDay();
  return {date,weekday,type:'practice',ownerId:null,eventLocation:'',traineeIds:[]};
 }).filter(row=>[0,3,5,6].includes(row.weekday));
}
export const monthlyBasketRollover=onSchedule(
 {schedule:'0 0 1 * *',timeZone:'Asia/Tokyo',region:'asia-northeast1'},
 async event=>{
  const runAt=new Date(event.scheduleTime||Date.now());
  const {month,day}=clockInTokyo(runAt);
  if(day!==1){console.warn('Not the first of month in JST; skip',runAt.toISOString());return;}
  const createMonth=plus(month,3),lockMonth=plus(month,1);
  if(createMonth<'2027-01'||createMonth>'2027-11'){
   console.log('Outside initial operating period',createMonth);return;
  }
  const lockRef=db.doc('teams/'+TEAM+'/months/'+lockMonth);
  const newRef=db.doc('teams/'+TEAM+'/months/'+createMonth);
  const practiceDays=provisionalDays(createMonth);
  const scheduledMillis=atJstStart(month);
  await db.runTransaction(async tx=>{
   // Read before writing. Replays must not replace existing manager edits.
   const [newSnap,lockSnap]=await Promise.all([tx.get(newRef),tx.get(lockRef)]);
   if(!newSnap.exists()){
    tx.create(newRef,{
     publication:'draft',
     scheduleStatus:'awaiting-manager',
     scheduleVerified:false,
     inputState:'closed', // must be approved and published before any parent response
     openAt:Timestamp.fromMillis(atJstStart(month)),
     cutoffAt:Timestamp.fromMillis(atJstStart(plus(createMonth,-1))),
     autoGenerated:true,
     createdBy:'monthlyBasketRollover',
     createdAt:FieldValue.serverTimestamp(),
     updatedAt:FieldValue.serverTimestamp(),
     version:1
    });
    for(const row of practiceDays){
     tx.create(newRef.collection('days').doc(row.date),{
      ...row,
      activityVerified:false,
      updatedAt:FieldValue.serverTimestamp()
     });
    }
   }
   if(lockSnap.exists()&&lockSnap.data()?.inputState==='open'){
    const closeAt=lockSnap.data()?.cutoffAt?.toMillis?.();
    // Respect a future deadline explicitly extended by the manager.
    if(!Number.isFinite(closeAt)||closeAt<=scheduledMillis){
     tx.update(lockRef,{inputState:'closed',updatedAt:FieldValue.serverTimestamp()});
    }
   }
  });
  console.log('Rollover checked', {lockMonth,createMonth,practiceDays:practiceDays.length});
 });
