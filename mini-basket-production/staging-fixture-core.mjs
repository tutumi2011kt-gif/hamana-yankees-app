// Fixtures for a separate QA project only. All names are fictitious.
// Pure data builder; does not connect to Firebase, and does not modify production.
import {preliminaryPracticeDays,jstInputOpenMillis,jstInputCutoffMillis} from './month-rollover-core.mjs';
import {isDayAllowed} from './weekday-conditions.mjs';
import {assertStagingFirebaseConfig} from './staging-config-guard.mjs';

export const QA_TEAM_ID='aritama-mini-basket';
export const QA_PUBLISHED_MONTH='2027-01';
export const QA_DRAFT_MONTH='2027-03';
export const QA_START='2026-12-01';
export const QA_MARKER_ID='staging-fixtures-v1';

export function makeQaMembers(){
 return Array.from({length:12},(_,index)=>{
  const n=index+1;
  return {
   id:'qa'+String(n).padStart(2,'0'),
   name:'テスト'+String(n).padStart(2,'0'),
   kana:'てすと'+String(n).padStart(2,'0'),
   status:'active',startDate:'2026-12-01',endDate:null,
   days:[0,3,5,6],preferredWeekdays:[],weekdayRule:'hard',weekdayNote:'検証専用：水・金・土・日',
   approvedWeekendDates:[]
  };
 });
}
export function makeQaDays(month,persons,{published=false}={}){
 const preliminary=preliminaryPracticeDays(month);
 return preliminary.map((row,index)=>{
  const type=published&&index===3?'game':published&&index===4?'rest':'practice';
  const assigned=type==='practice'&&published?persons[index%persons.length]:null;
  if(assigned&&!isDayAllowed(assigned,row.date,row.weekday))
   throw Error('検証用の曜日条件と担当者が一致しません');
  return {
   ...row,type,ownerId:assigned?.id??null,activityVerified:published,
   confirmedSubstituteId:null,confirmedSwapAt:null,confirmedSwapBy:null
  };
 });
}
export function makeQaMonthMeta(month,{published=false}={}){
 return {
  publication:published?'published':'draft',
  scheduleStatus:published?'provisional-published':'awaiting-manager',
  scheduleVerified:published,
  inputState:published?'open':'closed',
  openAtMillis:jstInputOpenMillis(month),
  cutoffAtMillis:jstInputCutoffMillis(month),
  autoGenerated:!published,
  createdBy:'qa-fixture-only',
  version:1
 };
}
export function makeQaFixture(projectId){
 assertStagingFirebaseConfig({projectId,authDomain:projectId+'.firebaseapp.com',apiKey:'fixture-validation-only',appId:'fixture-validation-only'});
 const members=makeQaMembers();
 const janDays=makeQaDays(QA_PUBLISHED_MONTH,members,{published:true});
 const marchDays=makeQaDays(QA_DRAFT_MONTH,members);
 const qaMembers=members.map(({id,...data})=>({id,data}));
 const published=makeQaMonthMeta(QA_PUBLISHED_MONTH,{published:true});
 const pending=makeQaMonthMeta(QA_DRAFT_MONTH);
 const roster=members.map(({id,name,kana,status})=>({id,name,kana,status}));
 const entries=[
  {path:'teams/'+QA_TEAM_ID+'/public/roster',data:{members:roster,publishedMonths:[QA_PUBLISHED_MONTH],qaOnly:true}},
  {path:'teams/'+QA_TEAM_ID+'/months/'+QA_PUBLISHED_MONTH,data:published},
  {path:'teams/'+QA_TEAM_ID+'/months/'+QA_DRAFT_MONTH,data:pending},
  ...qaMembers.map(({id,data})=>({path:'teams/'+QA_TEAM_ID+'/members/'+id,data})),
  ...janDays.map(({date,...data})=>({path:'teams/'+QA_TEAM_ID+'/months/'+QA_PUBLISHED_MONTH+'/days/'+date,data:{date,...data}})),
  ...marchDays.map(({date,...data})=>({path:'teams/'+QA_TEAM_ID+'/months/'+QA_DRAFT_MONTH+'/days/'+date,data:{date,...data}}))
 ];
 const paths=entries.map(x=>x.path);
 if(new Set(paths).size!==entries.length)throw Error('テスト初期データのドキュメントが重複しています');
 if(entries.some(x=>x.path.includes('2026-12')||x.path.includes('2027-02')))
  throw Error('検証用データに不要な既存月が含まれています');
 return {projectId,teamId:QA_TEAM_ID,
  markerPath:'teams/'+QA_TEAM_ID+'/qaSetup/'+QA_MARKER_ID,
  publishedMonth:QA_PUBLISHED_MONTH,draftMonth:QA_DRAFT_MONTH,
  members,janDays,marchDays,entries};
}
