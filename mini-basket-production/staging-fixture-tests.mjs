import assert from 'node:assert/strict';
import {makeQaFixture,makeQaMembers,makeQaMonthMeta,QA_PUBLISHED_MONTH,QA_DRAFT_MONTH} from './staging-fixture-core.mjs';
import {preliminaryPracticeDays,jstInputOpenMillis,jstInputCutoffMillis} from './month-rollover-core.mjs';
import {isDayAllowed} from './weekday-conditions.mjs';
let n=0;const test=(name,fn)=>{fn();n++;console.log('OK '+name)};
const fx=makeQaFixture('basket-staging-qa'),members=makeQaMembers();
test('all 12 fictitious members distinct',()=>{
 assert.equal(members.length,12);
 assert.equal(new Set(members.map(m=>m.id)).size,12);
 assert.ok(members.every(m=>m.name.startsWith('テスト')&&m.startDate==='2026-12-01'));
});
test('no real parent names',()=>{
 const listed=members.map(m=>m.name).join('|');
 for(const forbidden of ['ゆい','みあ','あん','まい','のどか','なぎさ','さやか','こはる','村松さわ','大竹わかな','かほ','はるか'])
  assert.ok(!listed.includes(forbidden));
});
test('public roster shares only minimal member data',()=>{
 const p=fx.entries.find(x=>x.path.endsWith('/public/roster')).data;
 assert.deepEqual(p.publishedMonths,['2027-01']);
 assert.equal(p.members.length,12);
 assert.ok(p.members.every(m=>Object.keys(m).sort().join(',')==='id,kana,name,status'));
});
test('January is published and currently editable in Nov 2026',()=>{
 const m=makeQaMonthMeta(QA_PUBLISHED_MONTH,{published:true});
 assert.equal(m.publication,'published');assert.equal(m.inputState,'open');
 assert.equal(m.openAtMillis,jstInputOpenMillis('2027-01'));
 assert.equal(m.cutoffAtMillis,jstInputCutoffMillis('2027-01'));
 assert.equal(m.cutoffAtMillis,Date.parse('2026-12-01T00:00:00+09:00'));
});
test('Jan has one role per practice, and real-game/rest have no owner',()=>{
 assert.equal(fx.janDays.length,preliminaryPracticeDays('2027-01').length);
 assert.equal(fx.janDays.filter(d=>d.type==='game').length,1);
 assert.equal(fx.janDays.filter(d=>d.type==='rest').length,1);
 assert.ok(fx.janDays.filter(d=>d.type!=='practice').every(d=>d.ownerId===null));
 assert.ok(fx.janDays.filter(d=>d.type==='practice').every(d=>
  members.some(m=>m.id===d.ownerId&&isDayAllowed(m,d.date,d.weekday))));
});
test('March is manager-only unverified draft',()=>{
 const m=makeQaMonthMeta(QA_DRAFT_MONTH);
 assert.equal(m.publication,'draft');assert.equal(m.inputState,'closed');
 assert.equal(m.scheduleVerified,false);assert.equal(m.autoGenerated,true);
 assert.ok(fx.marchDays.every(d=>d.ownerId===null&&d.activityVerified===false));
});
test('all fixture docs are unique and in QA team path',()=>{
 assert.ok(fx.entries.every(e=>e.path.startsWith('teams/aritama-mini-basket/')));
 assert.equal(new Set(fx.entries.map(e=>e.path)).size,fx.entries.length);
 assert.ok(fx.entries.every(e=>!e.path.includes('/answers/')));
 assert.ok(fx.entries.every(e=>!e.path.includes('/dutyLedger/')));
});
test('reject production project and misleading QA domain',()=>{
 assert.throws(()=>makeQaFixture('aritama-mini-basket'));
 assert.throws(()=>makeQaFixture('some-production-project'));
});
console.log('PASS '+n+' QA fixture sanity checks');
